# 1-masal kiritilgan sonning kvadrati va kubini chiqaruvchi dastur
son = int(input("Istalgan son kiriting: "))
print(f"{son} ning kvadrati {son ** 2} ga teng")
print(f"{son} ning kubi {son ** 3} ga teng")



# 2-MASALA: foydalanuvchi yoshini kiritadi, dastur tug‘ilgan yilni chiqaradi
